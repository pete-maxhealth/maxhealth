#!/usr/bin/env python3
"""Where each MaxedHealth feature works. One list, one score. Run: python3 tools/works_on.py [--write]
F = fully works, L = works with a limit (note says what), N = not available. Score: F=1, L=0.5, N=0. 'Fully' counts F only.
iPhone column is from the app's own code checks (BarcodeDetector, notifications) and Safari's published support; NOT yet tested on a real iPhone.
Premium rows are counted separately because Premium is Android only."""
import sys, re, html
# (group, feature, android, iphone, pc, note)
FREE = [
 ('Logging','Type or search a food, pick from your library','F','F','F',''),
 ('Logging','Recipes, ingredients, cupboards and stock, shopping list','F','F','F',''),
 ('Logging','27 starter packs','F','F','F',''),
 ('Logging','Voice logging and voice menu commands','F','L','F','iPhone Safari voice recognition is less reliable'),
 ('Logging','Barcode: live camera scan','F','L','L','Live scan needs Chrome on Android; elsewhere you take a photo of the barcode instead'),
 ('Logging','Label photo read and AI food search','F','F','F','Needs internet'),
 ('Logging','Read aloud','F','F','F',''),
 ('Logging','Manual entry for any day','F','F','F',''),
 ('Insight','Trends, patterns, compare two periods','F','F','F',''),
 ('Insight','Reports, PDF and share with someone','F','F','F',''),
 ('Insight','Ask AI about a period','F','F','F','Needs internet'),
 ('Insight','Fasting, water, fibre, supplements','F','F','F',''),
 ('Insight','Symptoms, treatments, lab results','F','F','F',''),
 ('Insight','Exercise, steps, body composition','F','F','F',''),
 ('Insight','Wearable data typed in or imported from a file','F','F','F',''),
 ('Insight','Bulk CSV upload (one template, many days)','F','F','F',''),
 ('Yours','8 languages, themes, organisation branding','F','F','F',''),
 ('Yours','Show/hide and reorder every card','F','F','F',''),
 ('Yours','Demo with 29 example people','F','F','F',''),
 ('Yours','Carer / family share (opt-in)','F','F','F',''),
 ('Yours','Works offline','F','L','F','On iPhone, add it to the Home Screen or Safari may clear the data after a week unused'),
 ('Yours','Reminders and notifications','F','L','F','iPhone needs iOS 16.4+ and the app on the Home Screen'),
 ('Data','Export and import backups (file)','F','F','F',''),
 ('Data','Phone-to-phone transfer by QR code','F','L','L','Reading the QR needs Chrome; use a backup file instead'),
 ('Data','Daily backup and local server tools','L','N','L','Needs the server on Android or a PC; the Premium launcher automates it'),
]
PREMIUM = [
 ('Automatic wearable sync (Health Connect)','Y','N','N'),
 ('Device ranking and daily self-checks','Y','N','N'),
 ('Automatic daily backup on the phone','Y','N','N'),
 ('Auto-update','Y','N','N'),
]
def score(col):
    v = [r[col] for r in FREE]; n = len(v)
    return round(100*sum({'F':1,'L':.5,'N':0}[x] for x in v)/n), round(100*v.count('F')/n), round(100*(n-v.count('N'))/n), n
PREMIUM_STEPS, SECS = 5, 30
PREMIUM_MIN = round(PREMIUM_STEPS*SECS/60, 1); PREMIUM_HRS = round(PREMIUM_MIN*365/60)
S = {name: score(i) for name, i in (('Android',2),('iPhone',3),('PC',4))}
if __name__ == '__main__':
    for k, (sc, full, part, n) in S.items(): print(f'{k}: score {sc}%  fully {full}%  at least partly {part}%  of {n} features')
    if '--write' in sys.argv:
        sym = {'F':'<span class="tick">✓</span>','L':'<span class="partial">◐</span>','N':'<span class="cross">—</span>'}
        rows = ''; g = None
        for grp, feat, a, i, p, note in FREE:
            rows += f'<tr><td>{html.escape(feat)}{(" <span style=\"color:var(--text3);font-size:12px;\">— "+html.escape(note)+"</span>") if note else ""}</td><td>{sym[a]}</td><td>{sym[i]}</td><td>{sym[p]}</td></tr>\n'
        pr = ''.join(f'<tr><td>{html.escape(f)}</td><td><span class="tick">✓</span></td><td><span class="cross">—</span></td><td><span class="cross">—</span></td></tr>\n' for f, *_ in PREMIUM)
        block = f'''<!-- WORKS-ON:START (generated by tools/works_on.py) -->
    <div class="tradeoffs" id="works-on">
      <div class="tradeoffs-label">Where it works</div>
      <div class="tradeoff">Of the {S['Android'][3]} everyday features of the free app, counting a feature with a limit as half: <strong>Android {S['Android'][0]}%</strong>, <strong>PC browser {S['PC'][0]}%</strong>, <strong>iPhone {S['iPhone'][0]}%</strong>. Fully working with no limit: Android {S['Android'][1]}%, PC {S['PC'][1]}%, iPhone {S['iPhone'][1]}%. The iPhone figures come from checking what the app needs against what Safari offers; they have not yet been tested on a real iPhone.</div>
      <div class="tradeoff">Premium, coming soon, does the daily typing for you: weight, steps, sleep, heart rate and the daily backup. At an estimated 30 seconds each, that is about {PREMIUM_MIN} minutes a day, or roughly {PREMIUM_HRS} hours a year. It is an estimate, and it depends on how much you log.</div>
      <details style="margin-top:12px;"><summary style="cursor:pointer;color:var(--accent);">See every feature</summary>
      <div class="compare-wrap"><table><thead><tr><th>Feature</th><th>Android</th><th>iPhone</th><th>PC</th></tr></thead><tbody>
{rows}{pr}</tbody></table></div>
      <div class="tradeoff" style="border-bottom:none;"><span class="tick">✓</span> works &nbsp; <span class="partial">◐</span> works with a limit &nbsp; <span class="cross">—</span> not available. The last four rows are Premium, which is coming soon and runs on Android.</div></details>
    </div>
<!-- WORKS-ON:END -->'''
        p = 'docs/story.html'; s = open(p).read()
        if 'WORKS-ON:START' in s: s = re.sub(r'<!-- WORKS-ON:START.*?WORKS-ON:END -->', lambda m: block, s, flags=re.S)
        else:
            k = s.index('<p class="prose">If you need hand-held onboarding'); s = s[:k] + block + '\n\n    ' + s[k:]
        open(p, 'w').write(s); print('written', p)
        g = 'docs/user-guide.html'; u = open(g).read()
        line = f'<!-- WORKS-ON-GUIDE:START --><p style="margin:14px 0;"><strong>Where it works.</strong> Of the {S["Android"][3]} everyday features of the free app, counting a feature with a limit as half: Android {S["Android"][0]}%, PC browser {S["PC"][0]}%, iPhone {S["iPhone"][0]}%. The few limits (live barcode scan, QR reading, voice and notifications on iPhone) are listed feature by feature on the <a href="story.html#works-on">story page</a>.</p><!-- WORKS-ON-GUIDE:END -->'
        if 'WORKS-ON-GUIDE:START' in u: u = re.sub(r'<!-- WORKS-ON-GUIDE:START.*?WORKS-ON-GUIDE:END -->', lambda m: line, u, flags=re.S)
        else:
            k = u.index('<h3 style="margin:22px 0 8px;">Free web app</h3>'); u = u[:k] + line + '\n\n  ' + u[k:]
        open(g, 'w').write(u); print('written', g)
